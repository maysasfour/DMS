String t(BuildContext context, WidgetRef ref, String key) {
  final lang = ref.watch(localeProvider).languageCode;
  return _strings[lang]?[key] ?? _strings['en']?[key] ?? key;
}

extension BuildContextTranslate on BuildContext {
  String tr(WidgetRef ref, String key) => t(this, ref, key);
}

/// Non-reactive lookup by language code — for use outside widget tree.
/// Falls back to English if key missing in target language.
String appString(String key, String languageCode) {
  return _strings[languageCode]?[key] ?? _strings['en']?[key] ?? key;
}
